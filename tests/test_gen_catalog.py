from __future__ import annotations

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]
SCRIPT = PROJECT_ROOT / "scripts" / "gen_catalog.py"


NIM_GAME = '''
[[games]]
key = "rs-nim"
title = "Nim"
title_ja = "ニム"
summary = "Play Nim against a CPU."
summary_ja = "CPU と Nim を対戦します．"
tags = ["strategy", "tui"]
'''.lstrip()


class CatalogIntegrationTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp_dir = tempfile.TemporaryDirectory(dir=PROJECT_ROOT)
        self.root = Path(self.temp_dir.name)
        (self.root / "games.toml").write_text(NIM_GAME, encoding="utf-8")
        (self.root / "README.md").write_text(
            "before\n<!-- BEGIN:games old text -->\nstale\n<!-- END:games -->\nafter\n",
            encoding="utf-8",
        )
        (self.root / "README.ja.md").write_text(
            "前\n<!-- BEGIN:games -->\n古い\n<!-- END:games -->\n後\n",
            encoding="utf-8",
        )

    def tearDown(self) -> None:
        self.temp_dir.cleanup()

    def run_catalog(self, *args: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(SCRIPT), "--root", str(self.root), *args],
            text=True,
            capture_output=True,
            check=False,
        )

    def test_generates_bilingual_tables_normalizes_markers_and_is_idempotent(self) -> None:
        first = self.run_catalog()
        self.assertEqual(first.returncode, 0, first.stderr)

        english = (self.root / "README.md").read_text(encoding="utf-8")
        japanese = (self.root / "README.ja.md").read_text(encoding="utf-8")
        marker = "<!-- BEGIN:games (auto-generated by scripts/gen_catalog.py — edit games.toml then re-run) -->"
        self.assertIn(marker, english)
        self.assertIn("1 game(s).", english)
        self.assertIn("| Game | Summary | Tags | Repo |", english)
        self.assertIn(
            "| [Nim](https://github.com/akitenkrad/rs-nim) | Play Nim against a CPU. | `strategy` `tui` | "
            "[rs-nim](https://github.com/akitenkrad/rs-nim) |",
            english,
        )
        self.assertTrue(english.startswith("before\n"))
        self.assertTrue(english.endswith("after\n"))
        self.assertIn(marker, japanese)
        self.assertIn("1 本のゲームを収録しています．", japanese)
        self.assertIn("| ゲーム | 概要 | タグ | リポジトリ |", japanese)
        self.assertIn("| [ニム](https://github.com/akitenkrad/rs-nim) | CPU と Nim を対戦します．", japanese)

        snapshot = (english, japanese)
        second = self.run_catalog()
        self.assertEqual(second.returncode, 0, second.stderr)
        self.assertEqual(
            snapshot,
            (
                (self.root / "README.md").read_text(encoding="utf-8"),
                (self.root / "README.ja.md").read_text(encoding="utf-8"),
            ),
        )
        checked = self.run_catalog("--check")
        self.assertEqual(checked.returncode, 0, checked.stderr)

    def test_check_reports_a_unified_diff_without_writing(self) -> None:
        self.assertEqual(self.run_catalog().returncode, 0)
        readme = self.root / "README.md"
        broken = readme.read_text(encoding="utf-8").replace("Play Nim", "BROKEN")
        readme.write_text(broken, encoding="utf-8")

        checked = self.run_catalog("--check")

        self.assertEqual(checked.returncode, 1)
        self.assertEqual(readme.read_text(encoding="utf-8"), broken)
        self.assertIn("--- README.md (current)", checked.stdout)
        self.assertIn("+++ README.md (generated)", checked.stdout)

    def test_rejects_missing_duplicate_and_invalid_keys(self) -> None:
        cases = {
            "missing": (
                NIM_GAME.replace('title_ja = "ニム"\n', ""),
                "games.toml: game #1 (rs-nim): missing required key: title_ja",
            ),
            "duplicate": (
                NIM_GAME + "\n" + NIM_GAME,
                "games.toml: game #2 (rs-nim): duplicate key: rs-nim",
            ),
            "invalid": (
                NIM_GAME.replace('key = "rs-nim"', 'key = "Nim"'),
                "games.toml: game #1 (Nim): invalid key",
            ),
        }
        for name, (contents, message) in cases.items():
            with self.subTest(name=name):
                (self.root / "games.toml").write_text(contents, encoding="utf-8")
                result = self.run_catalog()
                self.assertEqual(result.returncode, 1)
                self.assertIn(message, result.stderr)

    def test_rejects_gitmodules_mismatch_in_both_directions(self) -> None:
        (self.root / ".gitmodules").write_text(
            '[submodule "games/rs-other"]\n'
            "\tpath = games/rs-other\n"
            "\turl = https://github.com/akitenkrad/rs-other.git\n",
            encoding="utf-8",
        )

        result = self.run_catalog()

        self.assertEqual(result.returncode, 1)
        self.assertIn(".gitmodules: missing submodule path for games.toml game rs-nim: games/rs-nim", result.stderr)
        self.assertIn(".gitmodules: submodule under games/ is not listed in games.toml: games/rs-other", result.stderr)

    def test_rejects_readme_without_markers(self) -> None:
        (self.root / "README.md").write_text("no catalog here\n", encoding="utf-8")

        result = self.run_catalog()

        self.assertEqual(result.returncode, 1)
        self.assertIn("README.md: games catalog markers not found", result.stderr)

    def test_escapes_vertical_bars_in_generated_cells(self) -> None:
        contents = NIM_GAME.replace("Play Nim against a CPU.", "Plan | play")
        (self.root / "games.toml").write_text(contents, encoding="utf-8")

        result = self.run_catalog()

        self.assertEqual(result.returncode, 0, result.stderr)
        english = (self.root / "README.md").read_text(encoding="utf-8")
        self.assertIn("Plan \\| play", english)


if __name__ == "__main__":
    unittest.main()
